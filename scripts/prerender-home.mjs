import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {renderHome} from '../js/ui.js';
import {clubs} from '../data/game-squads.js';
import {statistics} from '../js/storage.js';

// Use the same public home as the browser, without reading anyone's saved games.
export function prerenderHome(source) {
  const main=/<main\b(?=[^>]*\bid="app")[^>]*>[\s\S]*?<\/main>/;
  if(!main.test(source))throw new Error('The app container is missing from index.html.');
  const content=renderHome({clubs,stats:statistics([])});
  return source.replace(main,()=>`<main id="app" tabindex="-1" aria-live="polite" data-screen="home" data-mode="world-cup">\n    <!-- Public home generated by scripts/prerender-home.mjs. -->\n    ${content}\n  </main>`);
}

export function syncHome(root=process.cwd()) {
  const file=path.join(root,'index.html'),source=fs.readFileSync(file,'utf8');
  const rendered=prerenderHome(source);
  if(rendered!==source)fs.writeFileSync(file,rendered);
}

if(process.argv[1]&&fileURLToPath(import.meta.url)===path.resolve(process.argv[1])) {
  syncHome();
  console.log('Página inicial disponível no HTML, antes do JavaScript.');
}
