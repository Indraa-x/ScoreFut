/** Replace the requested seasons without changing the other four eras of a club. */
export function replaceClubEras(clubs){
 return clubs.map(club=>{
  const replacement=RECENT_CLUB_ERAS.find(era=>era.clubId===club.id);
  if(!replacement)return club;
  return {...club,temporadas:club.temporadas.map(season=>season.ano===replacement.replaceYear?{
   ano:replacement.ano,conquistas:replacement.conquistas,
   jogadores:replacement.jogadores.map(player=>({...player,tags:[...player.tags],atributos:{...player.atributos}})),
  }:season)};
 });
}
